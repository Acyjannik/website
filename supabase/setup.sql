create extension if not exists pgcrypto;

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade
);

create table if not exists public.site_settings (
  id boolean primary key default true,
  brand_name text not null default 'ACYJANNIK',
  hero_kicker text not null default 'GAMING · STREAMING · COMMUNITY',
  hero_title text not null default 'ACYJANNIK',
  hero_description text not null default 'Willkommen im digitalen Zuhause von Acyjannik. Streams, Games und der ACY Club an einem Ort.',
  about_text text not null default 'Gaming, Streaming und eine Community, die weit über einen Stream hinausgeht.',
  community_title text not null default 'WELCOME TO THE ACY CLUB',
  community_text text not null default 'Mehr als nur ein Chat. Die Community rund um Acyjannik.',
  hero_image_url text default '/assets/acyjannik-hero.png',
  updated_at timestamptz not null default now()
);

create table if not exists public.social_links (
  id bigint generated by default as identity primary key,
  platform text unique not null,
  label text not null,
  url text not null,
  enabled boolean not null default true,
  sort_order integer not null default 0,
  updated_at timestamptz not null default now()
);

create table if not exists public.games (
  id bigint generated by default as identity primary key,
  name text unique not null,
  description text,
  tag text,
  image_url text,
  featured boolean not null default false,
  sort_order integer not null default 0,
  enabled boolean not null default true,
  updated_at timestamptz not null default now()
);

