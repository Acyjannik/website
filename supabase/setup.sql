-- Enable RLS
alter table public.admin_users enable row level security;
alter table public.site_settings enable row level security;
alter table public.social_links enable row level security;
alter table public.games enable row level security;

-- Public read policies
drop policy if exists "public can read settings" on public.site_settings;
create policy "public can read settings"
on public.site_settings for select
to anon, authenticated
using (true);

drop policy if exists "public can read social links" on public.social_links;
create policy "public can read social links"
on public.social_links for select
to anon, authenticated
using (enabled = true);

drop policy if exists "public can read games" on public.games;
create policy "public can read games"
on public.games for select
to anon, authenticated
using (enabled = true);

-- Admin access policies
drop policy if exists "admins can read admin_users" on public.admin_users;
create policy "admins can read admin_users"
on public.admin_users for select
to authenticated
using (user_id = auth.uid());

drop policy if exists "admins can write settings" on public.site_settings;
create policy "admins can write settings"
on public.site_settings for all
to authenticated
using (exists (select 1 from public.admin_users a where a.user_id = auth.uid()))
with check (exists (select 1 from public.admin_users a where a.user_id = auth.uid()));

drop policy if exists "admins can write socials" on public.social_links;
create policy "admins can write socials"
on public.social_links for all
to authenticated
using (exists (select 1 from public.admin_users a where a.user_id = auth.uid()))
with check (exists (select 1 from public.admin_users a where a.user_id = auth.uid()));

drop policy if exists "admins can write games" on public.games;
create policy "admins can write games"
on public.games for all
to authenticated
using (exists (select 1 from public.admin_users a where a.user_id = auth.uid()))
with check (exists (select 1 from public.admin_users a where a.user_id = auth.uid()));

