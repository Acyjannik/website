-- ACY CLUB V11 — Twitch profiles, stream attendance, watch points and V18.9 rewards

create table if not exists public.club_twitch_accounts (
  user_id uuid primary key references auth.users(id) on delete cascade,
  twitch_user_id text not null unique,
  login text,
  display_name text,
  profile_image_url text,
  email text,
  access_token text not null,
  refresh_token text not null,
  expires_at timestamptz,
  scopes text[] not null default '{}',
  connected_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_club_twitch_accounts_twitch_user on public.club_twitch_accounts(twitch_user_id);
alter table public.club_twitch_accounts enable row level security;
drop policy if exists "members read own twitch account" on public.club_twitch_accounts;
create policy "members read own twitch account" on public.club_twitch_accounts for select to authenticated using (user_id = auth.uid());

create table if not exists public.club_twitch_stream_sessions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  stream_id text,
  stream_date date not null default current_date,
  started_at timestamptz not null default now(),
  last_heartbeat timestamptz not null default now(),
  ended_at timestamptz,
  active boolean not null default true,
  duration_seconds integer not null default 0 check (duration_seconds >= 0),
  created_at timestamptz not null default now()
);

create index if not exists idx_twitch_sessions_user_date on public.club_twitch_stream_sessions(user_id,stream_date,started_at desc);
create index if not exists idx_twitch_sessions_active on public.club_twitch_stream_sessions(active,last_heartbeat desc);
create unique index if not exists idx_twitch_one_active_session_per_user on public.club_twitch_stream_sessions(user_id) where active = true;

alter table public.club_twitch_stream_sessions enable row level security;
drop policy if exists "members read own twitch sessions" on public.club_twitch_stream_sessions;
create policy "members read own twitch sessions" on public.club_twitch_stream_sessions for select to authenticated using (user_id = auth.uid());

create table if not exists public.club_twitch_points (
  user_id uuid primary key references auth.users(id) on delete cascade,
  watch_minutes integer not null default 0,
  watch_points integer not null default 0,
  stream_days integer not null default 0,
  current_stream_streak integer not null default 0,
  best_stream_streak integer not null default 0,
  last_stream_date date,
  first_stream_date date,
  updated_at timestamptz not null default now()
);

alter table public.club_twitch_points enable row level security;
drop policy if exists "members read own twitch points" on public.club_twitch_points;
create policy "members read own twitch points" on public.club_twitch_points for select to authenticated using (user_id = auth.uid());

